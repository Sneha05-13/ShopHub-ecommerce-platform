// Report Generator for Admin Panel

class ReportGenerator {
    constructor() {
        // Access the global db from firebase-config.js
        this.db = window.db || (typeof db !== 'undefined' ? db : null);
        
        if (!this.db) {
            console.error('Database not available. Make sure firebase-config.js is loaded first.');
        }
    }

    // Show notification helper
    showNotification(message, type = 'info') {
        // Try to use existing notification function or create alert fallback
        if (typeof showNotification === 'function') {
            showNotification(message, type);
        } else {
            alert(`${type.toUpperCase()}: ${message}`);
        }
    }

    // Generate CSV from data
    generateCSV(data, headers, filename) {
        let csvContent = headers.join(',') + '\n';
        
        data.forEach(row => {
            const values = headers.map(header => {
                const value = row[header] || '';
                // Escape commas and quotes in values
                const escapedValue = String(value).replace(/"/g, '""');
                return `"${escapedValue}"`;
            });
            csvContent += values.join(',') + '\n';
        });

        this.downloadFile(csvContent, filename, 'text/csv');
    }

    // Generate PDF report (simplified version)
    generatePDF(data, headers, title, filename) {
        // Create HTML content for PDF
        let htmlContent = `
            <!DOCTYPE html>
            <html>
            <head>
                <title>${title}</title>
                <style>
                    body { font-family: Arial, sans-serif; margin: 20px; }
                    h1 { color: #333; }
                    table { width: 100%; border-collapse: collapse; margin: 20px 0; }
                    th, td { border: 1px solid #ddd; padding: 8px; text-align: left; }
                    th { background-color: #f5f5f5; font-weight: bold; }
                    .footer { margin-top: 30px; font-size: 12px; color: #666; }
                </style>
            </head>
            <body>
                <h1>${title}</h1>
                <p>Generated on: ${new Date().toLocaleString()}</p>
                <table>
                    <thead>
                        <tr>
        `;

        headers.forEach(header => {
            htmlContent += `<th>${this.formatHeader(header)}</th>`;
        });

        htmlContent += `
                        </tr>
                    </thead>
                    <tbody>
        `;

        data.forEach(row => {
            htmlContent += '<tr>';
            headers.forEach(header => {
                htmlContent += `<td>${row[header] || ''}</td>`;
            });
            htmlContent += '</tr>';
        });

        htmlContent += `
                    </tbody>
                </table>
                <div class="footer">
                    <p>Report generated by ShopHub Admin Panel</p>
                </div>
            </body>
            </html>
        `;

        // Create a temporary window and print
        const printWindow = window.open('', '_blank');
        printWindow.document.write(htmlContent);
        printWindow.document.close();
        
        setTimeout(() => {
            printWindow.print();
            printWindow.close();
        }, 500);
    }

    // Download file
    downloadFile(content, filename, contentType) {
        const blob = new Blob([content], { type: contentType });
        const url = window.URL.createObjectURL(blob);
        const link = document.createElement('a');
        link.href = url;
        link.download = filename;
        document.body.appendChild(link);
        link.click();
        document.body.removeChild(link);
        window.URL.revokeObjectURL(url);
    }

    // Format header names
    formatHeader(header) {
        return header.replace(/([A-Z])/g, ' $1')
                   .replace(/^./, str => str.toUpperCase())
                   .trim();
    }

    // Format currency
    formatCurrency(amount) {
        return new Intl.NumberFormat('en-US', {
            style: 'currency',
            currency: 'USD'
        }).format(amount || 0);
    }

    // Format date
    formatDate(timestamp) {
        if (!timestamp) return 'N/A';
        try {
            if (timestamp && typeof timestamp.toDate === 'function') {
                return timestamp.toDate().toLocaleDateString();
            } else if (timestamp instanceof Date) {
                return timestamp.toLocaleDateString();
            }
            return 'N/A';
        } catch (error) {
            return 'N/A';
        }
    }
}

// Dashboard Reports
class DashboardReports extends ReportGenerator {
    async generateDashboardReport(format = 'csv') {
        if (!this.db) {
            this.showNotification('Database not available', 'error');
            return;
        }
        
        try {
            // Get dashboard data
            const productsSnapshot = await this.db.collection('products').get();
            const ordersSnapshot = await this.db.collection('orders').get();
            const usersSnapshot = await this.db.collection('users').get();

            // Calculate statistics
            const totalProducts = productsSnapshot.size;
            const totalOrders = ordersSnapshot.size;
            let totalRevenue = 0;
            const statusCounts = {};
            
            ordersSnapshot.forEach(doc => {
                const order = doc.data();
                totalRevenue += order.total || 0;
                const status = order.status || 'unknown';
                statusCounts[status] = (statusCounts[status] || 0) + 1;
            });

            const totalCustomers = usersSnapshot.docs.filter(doc => 
                doc.data().role === 'customer'
            ).length;

            const reportData = [{
                'Metric': 'Total Products',
                'Value': totalProducts,
                'Description': 'Number of products in inventory'
            }, {
                'Metric': 'Total Orders',
                'Value': totalOrders,
                'Description': 'Total number of orders placed'
            }, {
                'Metric': 'Total Revenue',
                'Value': this.formatCurrency(totalRevenue),
                'Description': 'Total revenue from all orders'
            }, {
                'Metric': 'Total Customers',
                'Value': totalCustomers,
                'Description': 'Number of registered customers'
            }];

            // Add order status breakdown
            Object.entries(statusCounts).forEach(([status, count]) => {
                reportData.push({
                    'Metric': `Orders - ${status}`,
                    'Value': count,
                    'Description': `Number of ${status} orders`
                });
            });

            const headers = ['Metric', 'Value', 'Description'];
            const filename = `dashboard-report-${new Date().toISOString().split('T')[0]}`;

            if (format === 'pdf') {
                this.generatePDF(reportData, headers, 'Dashboard Report', filename);
            } else {
                this.generateCSV(reportData, headers, `${filename}.csv`);
            }

        } catch (error) {
            console.error('Error generating dashboard report:', error);
            this.showNotification('Error generating dashboard report', 'error');
        }
    }

    async generateRecentOrdersReport(format = 'csv') {
        if (!this.db) {
            this.showNotification('Database not available', 'error');
            return;
        }
        
        try {
            const ordersSnapshot = await this.db.collection('orders')
                .orderBy('createdAt', 'desc')
                .limit(50)
                .get();

            const reportData = [];
            
            for (const doc of ordersSnapshot.docs) {
                const order = { id: doc.id, ...doc.data() };
                
                // Get customer name
                let customerName = order.userEmail;
                try {
                    const userDoc = await this.db.collection('users').doc(order.userId).get();
                    if (userDoc.exists) {
                        customerName = userDoc.data().name || order.userEmail;
                    }
                } catch (error) {
                    console.error('Error fetching user:', error);
                }

                reportData.push({
                    'Order ID': order.id.substring(0, 8),
                    'Customer': customerName,
                    'Email': order.userEmail,
                    'Date': this.formatDate(order.createdAt),
                    'Items': order.items ? order.items.length : 0,
                    'Subtotal': this.formatCurrency(order.subtotal),
                    'Tax': this.formatCurrency(order.tax),
                    'Total': this.formatCurrency(order.total),
                    'Status': order.status
                });
            }

            const headers = ['Order ID', 'Customer', 'Email', 'Date', 'Items', 'Subtotal', 'Tax', 'Total', 'Status'];
            const filename = `recent-orders-report-${new Date().toISOString().split('T')[0]}`;

            if (format === 'pdf') {
                this.generatePDF(reportData, headers, 'Recent Orders Report', filename);
            } else {
                this.generateCSV(reportData, headers, `${filename}.csv`);
            }

        } catch (error) {
            console.error('Error generating recent orders report:', error);
            this.showNotification('Error generating recent orders report', 'error');
        }
    }
}

